/**
 * Screenshots the ThemePicker menu OPEN in all three themes.
 *
 * App.tsx is untouched (see the header comment in ThemePicker.tsx for why),
 * so there is no real page yet that mounts <ThemePicker>. Rather than adding
 * a second entry to vite.config.ts — which would break `npm run build:single`
 * (it needs `inlineDynamicImports`, and rollup rejects that with more than
 * one entry; see that file's own comment) — this script builds its own tiny
 * harness ENTIRELY AT RUNTIME: it writes a throwaway HTML + TSX pair next to
 * vite.config.ts, points a one-off `vite build()` at it (same technique as
 * scripts/probe-ramp.mjs), and deletes both the generated sources and the
 * build output when it's done, win or lose. Nothing checked into the repo
 * changes.
 *
 * The harness renders a `.ws-topbar`-shaped strip with the picker at the
 * right end — the actual placement — and clicks the trigger open before
 * screenshotting, since the design calls for judging OPEN legibility (menu
 * background vs. row text vs. the active check) not just the closed pill.
 *
 * Serves a production build (not the dev server), same convention as
 * scripts/shots.mjs — what's captured is what actually ships.
 */
import { createServer } from 'node:http'
import { readFile, writeFile, rm } from 'node:fs/promises'
import { existsSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
import { build } from 'vite'
import react from '@vitejs/plugin-react'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'shots')
const DIST = path.join(ROOT, 'dist-theme-probe')
const HTML_NAME = 'theme-probe.generated.html'
const TSX_NAME = 'theme-probe.generated.tsx'
const HTML_PATH = path.join(ROOT, HTML_NAME)
const TSX_PATH = path.join(ROOT, TSX_NAME)

const HARNESS_HTML = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Weekspan — theme picker probe</title>
    <!-- Generated by scripts/probe-theme.mjs. Not part of the shipped app;
         deleted again as soon as the build this file feeds has run. -->
    <link
      href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&display=swap"
      rel="stylesheet"
    />
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/${TSX_NAME}"></script>
  </body>
</html>
`

const HARNESS_TSX = `import { StrictMode, useState } from 'react'
import { createRoot } from 'react-dom/client'
import { applyTheme, type ThemeChoice } from './src/theme.js'
import { ThemePicker } from './src/theme/ThemePicker.js'
import './src/styles/tokens.css'
import './src/styles/app.css'

/**
 * Generated by scripts/probe-theme.mjs — see that file. Mounts the real
 * ThemePicker inside a real .ws-topbar strip (surface behind it, panel top
 * bar, hairline border) so the screenshot shows it exactly where the design
 * places it: right end of the bar, immediately left of the date.
 */

const THEME_CHOICES: ReadonlySet<string> = new Set(['paper', 'solarized', 'warm'])
function isTheme(v: string | null): v is ThemeChoice {
  return v !== null && THEME_CHOICES.has(v)
}
const themeParam = new URLSearchParams(window.location.search).get('theme')
const initial: ThemeChoice = isTheme(themeParam) ? themeParam : 'paper'
applyTheme(initial)

function ThemeProbe(): JSX.Element {
  const [value, setValue] = useState<ThemeChoice>(initial)
  return (
    <div style={{ minHeight: '100vh', background: 'var(--ws-surface)' }}>
      <div className="ws-topbar">
        <span className="ws-filepicker">
          demo-week.ledger.md <span className="ws-caret">▾</span>
        </span>
        <span className="ws-topbar-spacer" />
        <ThemePicker
          value={value}
          onChange={(next) => {
            applyTheme(next)
            setValue(next)
          }}
        />
        <span className="ws-date">Mon 24 Aug</span>
        <span className="ws-week">W35</span>
      </div>
    </div>
  )
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <ThemeProbe />
  </StrictMode>,
)
`

const MIME = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2',
}

function serve(dist, port) {
  const server = createServer(async (req, res) => {
    const url = (req.url ?? '/').split('?')[0]
    const rel = url === '/' ? HTML_NAME : url.slice(1)
    const file = path.join(dist, rel)
    try {
      const body = await readFile(file)
      res.writeHead(200, { 'content-type': MIME[path.extname(file)] ?? 'application/octet-stream' })
      res.end(body)
    } catch {
      res.writeHead(404, { 'content-type': 'text/plain' })
      res.end('not found')
    }
  })
  return new Promise((resolve) => server.listen(port, () => resolve(server)))
}

const THEMES = ['paper', 'solarized', 'warm']
const PORT = 4331

let server
let browser
const errors = []

try {
  await writeFile(HTML_PATH, HARNESS_HTML)
  await writeFile(TSX_PATH, HARNESS_TSX)

  await build({
    root: ROOT,
    plugins: [react()],
    build: {
      outDir: DIST,
      emptyOutDir: true,
      rollupOptions: { input: HTML_NAME },
    },
    logLevel: 'error',
  })

  if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true })

  server = await serve(DIST, PORT)
  browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 480, height: 260 }, deviceScaleFactor: 2 })
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('console', (m) => {
    if (m.type() === 'error') errors.push(m.text())
  })

  for (const theme of THEMES) {
    await page.goto(`http://localhost:${PORT}/${HTML_NAME}?theme=${theme}`, { waitUntil: 'networkidle' })
    await page.evaluate(() => document.fonts.ready)
    await page.click('.ws-themepicker-trigger')
    // Menu render + focus-move settle before the shot.
    await page.waitForSelector('.ws-themepicker-menu')
    await page.waitForTimeout(100)
    await page.screenshot({ path: path.join(OUT, `theme-picker-${theme}.png`) })
    console.log(`shot: theme-picker-${theme}`)
  }

  console.log('')
  console.log('page errors:', errors.length ? errors.slice(0, 8) : 'none')
} finally {
  await browser?.close()
  server?.close()
  await rm(HTML_PATH, { force: true })
  await rm(TSX_PATH, { force: true })
  await rm(DIST, { recursive: true, force: true })
}

if (errors.length) process.exit(1)
